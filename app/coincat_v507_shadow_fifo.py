"""v50.7 non-custodial SHADOW-only portfolio FIFO using the unified lot engine.

Each price band owns a fresh SQLite :memory: database. No file-backed database,
account SDK, real ledger, or real order sender can be passed into this class.
The input is a HYPOTHETICAL route generated by the existing research planner;
its fee/price fields are only estimates. A quote touch is never a confirmed fill.
"""
from __future__ import annotations
from contextlib import closing
from decimal import Decimal, InvalidOperation, localcontext
import sqlite3
from coincat_unified_fifo_v501 import install, opening, balance, verify, _apply_one, UnifiedSettlementError

class ShadowFIFOBlocked(ValueError):
    pass

def exact(v, *, positive=False):
    if type(v) is bool or isinstance(v,float):
        raise ShadowFIFOBlocked('Exact numbers only; binary floats are not financial evidence')
    try:d=Decimal(str(v))
    except (InvalidOperation,ValueError,TypeError):raise ShadowFIFOBlocked('Invalid shadow decimal') from None
    if not d.is_finite() or d<0 or (positive and d==0):
        raise ShadowFIFOBlocked('Invalid nonpositive shadow quantity')
    return d

def _memory(db):
    dbs=db.execute('PRAGMA database_list').fetchall()
    if len(dbs)!=1 or dbs[0][2] != '':
        raise ShadowFIFOBlocked('Shadow FIFO only accepts a private SQLite :memory: database')

class ShadowFIFOPortfolio:
    """A session-local FIFO wallet; intentionally never exposes an exchange order API."""
    def __init__(self, starting_quantities, starting_usd_rates, *, label='MARKET_TAKER'):
        self.db=sqlite3.connect(':memory:',isolation_level=None)
        _memory(self.db)
        install(self.db)
        self.label=label
        self.start={}
        self.expected_usd={}
        self.scenarios=0
        self.legs=0
        self.replays=0
        self.refusals=0
        self.fees_estimated_usd=Decimal('0')
        self.last_error=None
        try:
            for raw_asset,raw_qty in (starting_quantities or {}).items():
                asset=str(raw_asset).upper()
                qty=exact(raw_qty)
                if not asset.isalnum() or asset != str(raw_asset) or qty==0:continue
                px=exact((starting_usd_rates or {})[asset],positive=True)
                opening(self.db,asset,qty,performance_usd=qty*px,tax_usd=None)
                self.start[asset]=qty
                self.expected_usd[asset]=px
            if not self.start:raise ShadowFIFOBlocked('No verified enrolled opening quantities')
            verify(self.db)
        except BaseException:
            self.db.close()
            raise

    def close(self):
        self.db.close()

    def balances(self):
        _memory(self.db)
        return {str(asset):exact(qty) for asset,qty in self.db.execute(
            'SELECT asset,qty FROM unified_v501_wallets') if exact(qty)>0}

    def mark_vs_hold(self, usd_rates):
        """Same-time total portfolio mark compared with no-trade frozen quantities."""
        rates={k:exact(usd_rates[k],positive=True) for k in set(self.start)|set(self.balances())}
        baseline=sum((qty*rates[asset] for asset,qty in self.start.items()),Decimal(0))
        current=sum((qty*rates[asset] for asset,qty in self.balances().items()),Decimal(0))
        return {'shadow_usd':current,'hold_usd':baseline,'delta_usd':current-baseline}

    def post_hypothetical_route(self, *, session_id, steps, usd_rates, at_utc):
        """Model exact FIFO for *all* SELL/BUY legs of one planned route, atomically.

        The function that posts each leg is the same _apply_one used by the
        unified confirmed-fill engine. It is called ONLY on our memory DB.
        All generated trade/order IDs are prefixed SHADOW; they cannot be
        accepted as authenticated Coinbase identity or fill evidence.
        """
        _memory(self.db)
        if not session_id or not str(session_id).startswith('SHADOW-') or not isinstance(at_utc,int) or at_utc<=0:
            raise ShadowFIFOBlocked('Fake-only identity/timestamp required')
        if not isinstance(steps,(tuple,list)) or not 1<=len(steps)<=128:
            raise ShadowFIFOBlocked('1–128 validated SHADOW-only route steps required')
        # Underlying FIFO uses Decimal with sub-satoshi dust precision.
        with localcontext() as ctx:
            ctx.prec=120
            marks={str(k):str(exact(v,positive=True)) for k,v in (usd_rates or {}).items()}
            self.db.execute('SAVEPOINT shadow_route')
            pending_fees=Decimal(0)
            statuses=[]
            try:
                for idx,s in enumerate(steps):
                    pair=str(s['pair']);base,quote=pair.split('-')
                    side=str(s['side']).upper()
                    qty=exact(s['gross_base_quantity'],positive=True)
                    spent=exact(s['input_quantity'],positive=True)
                    recv=exact(s['output_quantity'],positive=True)
                    rate=exact(s['fee_rate_used'])
                    if side not in ('BUY','SELL') or rate>=Decimal('.05'):
                        raise ShadowFIFOBlocked('Invalid research route side or fee')
                    # Simulated quote fee/cost is derived from route receipts,
                    # so it matches the planner's slippage and fee arithmetic.
                    if side=='BUY':
                        gross_quote=spent/(1+rate)
                        fee_amount=spent-gross_quote
                    else:
                        gross_quote=recv/(1-rate)
                        fee_amount=gross_quote-recv
                    for ccy in (base,quote):
                        if ccy!='USD' and ccy not in marks:
                            raise ShadowFIFOBlocked('Missing verified shadow USD mark for '+ccy)
                    record={'trade_id':f'{session_id}-F{idx}',
                        'order_id':f'{session_id}-O{idx}',
                        'product_id':pair,'side':side,
                        'base_qty':format(qty,'f'),
                        'price':format(gross_quote/qty,'f'),
                        'fee_amount':format(fee_amount,'f'),
                        'fee_currency':quote,'at_utc':at_utc+idx,
                        'usd_marks':marks}
                    state=_apply_one(self.db,record)
                    statuses.append(state)
                    if state=='REPLAY_SKIPPED':self.replays+=1
                    pending_fees+=fee_amount*(Decimal(1) if quote=='USD' else exact(marks[quote]))
                if 'REPLAY_SKIPPED' in statuses and 'APPLIED' in statuses:
                    raise ShadowFIFOBlocked('Partial duplicate route refused atomically')
                verify(self.db)
                self.db.execute('RELEASE shadow_route')
                if statuses and all(state=='REPLAY_SKIPPED' for state in statuses):
                    return {'state':'SHADOW_FIFO_REPLAY_NOOP','steps':0,'estimated_fee_usd':Decimal(0)}
                self.scenarios+=1;self.legs+=len(steps)
                self.fees_estimated_usd+=pending_fees
                return {'state':'SHADOW_FIFO_POSTED','steps':len(steps),'estimated_fee_usd':pending_fees}
            except BaseException as exc:
                self.db.execute('ROLLBACK TO shadow_route')
                self.db.execute('RELEASE shadow_route')
                self.refusals+=1
                self.last_error=type(exc).__name__
                raise
