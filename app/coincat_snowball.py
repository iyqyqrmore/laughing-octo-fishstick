"""v60.15 Snowball immediate USD research (observation only, never an order).

One existing costed one-order planner receipt is compared at CURRENT conservative
liquidation-side Coinbase REST books. Both portfolios are valued at the same
snapshot. No market order, ledger, network access or predictive alpha here.
Missing or asynchronous books always produce NOT_VERIFIED, never zero cost.
"""
from __future__ import annotations
from decimal import Decimal, InvalidOperation
from coincat_cross_quote import usd_conversion

SLIPPAGE = Decimal('0.0015')
MAX_AGE_S = 30
MAX_SKEW_S = 12


def dec(value):
    try:
        if isinstance(value, (bool,float)):return None
        d=Decimal(str(value))
        return d if d.is_finite() else None
    except (TypeError,ValueError,InvalidOperation):return None


def _valid_book(raw,now):
    try:
        bid,ask,ts=raw[:3]
        bid,ask=dec(bid),dec(ask)
        ts=float(ts)
        if bid is None or ask is None or bid<=0 or ask<bid or not 0<=now-ts<=MAX_AGE_S:return None
        if (ask-bid)/ask > Decimal('.0025'):return None
        return bid,ask,ts
    except (ValueError,TypeError,IndexError,OverflowError):return None


def _liquidation_usd(asset,books,*,now,route_pair,fee):
    if asset=='USD':return Decimal(1),()
    fx=usd_conversion(asset,books,now=now,max_age=MAX_AGE_S,max_legs=2)
    if (fx is None or not fx['path'] or (route_pair in fx['path'] and
            not (len(fx['path'])==1 and 'USD' in route_pair.split('-')))):
        return None
    stamps=[]
    for pair in fx['path']:
        valid=_valid_book(books.get(pair),now)
        if not valid:return None
        stamps.append(valid[2])
    # Conservative liquidation approximation: pay estimated taker friction
    # once per distinct hypothetical USD-mark liquidation order, equally for
    # source HOLD and destination. The entry order has ALREADY been charged.
    factor=((Decimal(1)-fee)*(Decimal(1)-SLIPPAGE))**len(fx['path'])
    return fx['rate']*factor,tuple(stamps)


def assess_idea(idea,quotes,*,now,taker_fee):
    """Assess existing single-leg planner receipts; NO entry pricing invented.

    Returns NOT_VERIFIED unless all direct and USD-mark books are sufficiently
    fresh and synchronized and the receipt matches its order-book side.
    'IMMEDIATE_ESTIMATE' means research-only, not a fill or certified arbitrage.
    """
    result={'state':'NOT_VERIFIED','delta_usd':None,'before_usd':None,'after_usd':None,
            'reason':'MISSING_OR_STALE_BOOKS','execution_authorized':False}
    fee=dec(taker_fee)
    if fee is None or not Decimal(0)<=fee<Decimal('.05'):
        result['reason']='FEE_UNVERIFIED';return result
    if not isinstance(idea,dict) or idea.get('sends_live_orders') is not False:
        result['reason']='NOT_RESEARCH_ONLY';return result
    steps=idea.get('shadow_fifo_steps') or ()
    if len(steps)!=1 or idea.get('source')=='MULTI':
        result['reason']='NOT_SINGLE_ORDER';return result
    step=steps[0]
    pair=str(step.get('pair','')).upper()
    src=str(idea.get('source','')).upper();dst=str(idea.get('target','')).upper()
    if not pair or not src or not dst or src==dst or src not in pair.split('-') or dst not in pair.split('-'):
        result['reason']='INVALID_ROUTE';return result
    book=_valid_book((quotes or {}).get(pair),float(now))
    if book is None:return result
    entry_fee=dec(step.get('fee_rate_used'))
    src_qty=dec(idea.get('input_units_planned'))
    dst_qty=dec(idea.get('destination_units_estimate'))
    if (entry_fee is None or abs(entry_fee-fee)>Decimal('.0000001') or
        src_qty is None or dst_qty is None or src_qty<=0 or dst_qty<=0):
        result['reason']='RECEIPT_OR_FEE_MISMATCH';return result
    # Do not accept a phantom positive delta generated by a stale modeled
    # receipt: compare the receipt's implied entry-side price to fresh book.
    gross=dec(step.get('gross_base_quantity'))
    spent=dec(step.get('input_quantity'));received=dec(step.get('output_quantity'))
    if gross is None or spent is None or received is None or min(gross,spent,received)<=0:
        result['reason']='RECEIPT_OR_FEE_MISMATCH';return result
    side=str(step.get('side','')).upper()
    try:
        implied=(spent/(1+fee)/gross if side=='BUY' else
                 received/(1-fee)/gross if side=='SELL' else None)
        expected=book[1] if side=='BUY' else book[0]
        if implied is None or abs(implied/expected-1)>Decimal('.0035'):
            result['reason']='ENTRY_PRICE_DRIFT';return result
    except (InvalidOperation,ZeroDivisionError):
        result['reason']='ENTRY_PRICE_DRIFT';return result
    src_mark=_liquidation_usd(src,quotes,now=float(now),route_pair=pair,fee=fee)
    dst_mark=_liquidation_usd(dst,quotes,now=float(now),route_pair=pair,fee=fee)
    if src_mark is None or dst_mark is None:return result
    stamps=(book[2],)+src_mark[1]+dst_mark[1]
    if max(stamps)-min(stamps)>MAX_SKEW_S:
        result['reason']='UNSYNCHRONIZED_BOOKS';return result
    before=src_qty*src_mark[0]
    after=dst_qty*dst_mark[0]
    delta=after-before
    result.update(state='IMMEDIATE_ESTIMATE',reason=('POSITIVE_ESTIMATE' if delta>0 else 'COST_DRAG'),
                  delta_usd=delta,before_usd=before,after_usd=after,
                  route_pair=pair,book_span_seconds=max(stamps)-min(stamps))
    return result


def screen(ideas,quotes,*,now,taker_fee,minimum_usd='0.10'):
    """Annotate read-only candidate copies; bounded in-memory scan, no new feed."""
    try:floor=dec(minimum_usd)
    except (TypeError,ValueError):floor=None
    if floor is None or floor<0:floor=Decimal('.10')
    totals={'screened':0,'priced':0,'positive':0,'above_floor':0,'reasons':{},
            'best_delta_usd':None,'best_before_usd':None,'best_after_usd':None,
            'fee_source':'ACCOUNT_TAKER_TIER_ESTIMATE_NOT_PAIR_PREVIEW',
            'status':'NO_IMMEDIATE_ADVANTAGE_VERIFIED','threshold_usd':str(floor),
            'live_order_authorized':False}
    output=[]
    for old in list(ideas or ())[:100]:
        if not isinstance(old,dict):continue
        idea=dict(old)
        evidence=assess_idea(idea,quotes,now=now,taker_fee=taker_fee)
        totals['screened']+=1
        reason=evidence['reason'];totals['reasons'][reason]=totals['reasons'].get(reason,0)+1
        delta=evidence.get('delta_usd')
        if evidence['state']=='IMMEDIATE_ESTIMATE':
            totals['priced']+=1
            if delta>0:
                totals['positive']+=1
                if delta>=floor:totals['above_floor']+=1
            if totals['best_delta_usd'] is None or delta>totals['best_delta_usd']:
                totals['best_delta_usd']=delta
                totals['best_before_usd']=evidence['before_usd']
                totals['best_after_usd']=evidence['after_usd']
        # Add exclusively to experimental research. Does not change P10 or OOS.
        idea['snowball_immediate_usd']=str(delta) if delta is not None else None
        idea['snowball_state']=evidence['state']
        idea['snowball_executable_verified']=False
        output.append(idea)
    if totals['above_floor']:
        totals['status']='PROVISIONAL_IMMEDIATE_GAIN_RESEARCH_ONLY'
    return output,totals


